/** Lingua scelta nelle Impostazioni (dec. 46): quella del sistema, italiano o inglese. */
export type LanguagePref = 'system' | 'it' | 'en';

const deviceLocale = Intl.DateTimeFormat().resolvedOptions().locale ?? 'it-IT';
const resolve = (p: LanguagePref) => (p === 'en' || (p === 'system' && deviceLocale.toLowerCase().startsWith('en')) ? 'en-US' : 'it-IT');

// `let` esportati: chi li importa legge sempre il valore attuale (binding ES live), perché tutti li usano dentro i componenti.
// Per ora si parte in italiano (dec. 149), come il valore iniziale delle Impostazioni.
export let locale = resolve('it');
export let t: Dict = locale === 'en-US' ? en : it;

/** Cambia lingua; i componenti si ridisegnano perché useTheme è iscritto alle Impostazioni. */
export function setLanguage(p: LanguagePref) {
  locale = resolve(p);
  t = locale === 'en-US' ? en : it;
}
