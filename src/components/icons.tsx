export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 24,
  color,
  strokeWidth = 2,
  style,
  accessibilityLabel,
}: {
  name: IconName;
  size?: number;
  color: string;
  strokeWidth?: number;
  style?: StyleProp<ViewStyle>;
  accessibilityLabel?: string;
}) {
  return <HugeiconsIcon icon={ICONS[name]} size={size} color={color} strokeWidth={strokeWidth} style={style} accessibilityLabel={accessibilityLabel} />;
}

